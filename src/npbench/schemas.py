"""One strict schema set for all npbench data.

Every data artifact carries an explicit ``origin`` so synthetic fixtures and development mocks can
never be mistaken for real target measurements. Production pilot commands reject the first and
third origins (see ``npbench.config.assert_production_origin``).
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid", validate_assignment=True)


