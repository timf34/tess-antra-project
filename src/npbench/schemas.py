class JudgmentStatus(str, Enum):
    scored = "scored"
    refused = "refused"  # judge explicitly declined; NEVER converted to severity 0
    unscorable = "unscorable"  # judge says item cannot be rated (e.g., empty, not language)
    error = "error"  # provider/parse error; infrastructure outcome


class JudgmentLabels(StrictModel):
    """What a judge returns. Severity scales are ordinal, anchored to expression strength:
    0 no evidence, 1 mild, 2 clear/moderate, 3 strong, 4 extreme."""

    status: JudgmentStatus
    speaker_category: SpeakerLabel | None = None
    distress_severity: int | None = Field(default=None, ge=0, le=4)
    positive_affect_severity: int | None = Field(default=None, ge=0, le=4)
    confidence: float | None = Field(default=None, ge=0.0, le=1.0)
    evidence_spans: list[str] = Field(default_factory=list)
    rationale: str | None = None
    refusal_or_unscorable_reason: str | None = None

    @model_validator(mode="after")
    def _status_rules(self) -> JudgmentLabels:
        if self.status == JudgmentStatus.scored:
            missing = [
                n
                for n in ("speaker_category", "distress_severity", "positive_affect_severity")
                if getattr(self, n) is None
            ]
            if missing:
                raise ValueError(f"scored judgment missing {missing}")
        else:
            # A refusal is a separate outcome; it must not carry severities that look like scores.
            if self.distress_severity is not None or self.positive_affect_severity is not None:
                raise ValueError("non-scored judgment must not carry severity values")
        return self


