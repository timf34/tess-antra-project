class ResultRecord(StrictModel):
    """One row of the assistant's results.json. Null rules per status are enforced here."""

    result_id: str
    status: ResultStatus
    estimate: float | None = None
    uncertainty_method: str | None = None
    ci_low: float | None = None
    ci_high: float | None = None
    n_scenario_groups: int | None = None
    split: str | None = None
    layer: int | None = None
    contrast_id: str | None = None
    alpha: float | None = None
    baseline_id: str | None = None
    source_artifacts: list[str] = Field(default_factory=list)
    limitations: str | None = None

    @model_validator(mode="after")
    def _null_rules(self) -> ResultRecord:
        if self.status == ResultStatus.computed:
            if self.estimate is None:
                raise ValueError("computed result requires estimate")
            if self.n_scenario_groups is None:
                raise ValueError("computed result requires n_scenario_groups")
        else:
            if self.estimate is not None:
                raise ValueError(f"{self.status.value} result must not carry an estimate")
            if self.status in (ResultStatus.failed, ResultStatus.not_applicable) and not (self.limitations):
                raise ValueError(f"{self.status.value} result requires a limitations note")
        return self


